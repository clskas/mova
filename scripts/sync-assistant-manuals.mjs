// Copies the user manuals into the driver-service assistant (the Docker image has no docs/ folder).
// Run after editing docs/user-manual/passager.md or chauffeur.md:  node scripts/sync-assistant-manuals.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8').replace(/\r\n/g, '\n');
const out = `// Generated by scripts/sync-assistant-manuals.mjs from docs/user-manual — do not edit by hand.
export const PASSENGER_MANUAL = ${JSON.stringify(read('docs/user-manual/passager.md'))};

export const DRIVER_MANUAL = ${JSON.stringify(read('docs/user-manual/chauffeur.md'))};
`;
writeFileSync(join(root, 'services/driver-service/src/assistant/manuals.generated.ts'), out);
console.log('assistant manuals synced');
