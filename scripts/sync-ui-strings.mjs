#!/usr/bin/env node
// Copies the French UI texts of the mobile app (keys of strings_en.dart) into
// packages/shared/src/ui-source-strings.ts: the server translates them into
// Swahili and Lingala. Run after adding texts to strings_en.dart.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dart = readFileSync(join(root, 'mobile/lib/core/i18n/strings_en.dart'), 'utf8');
const keys = [];
const re = /^\s*"((?:[^"\\]|\\.)*)"\s*:/gm;
for (let m; (m = re.exec(dart)); ) {
  // Dart escapes → the runtime string the app looks up.
  const value = m[1].replace(/\\(.)/g, (_, c) => ({ n: '\n', t: '\t', '"': '"', $: '$', '\\': '\\' })[c] ?? c);
  keys.push(value);
}
const unique = [...new Set(keys)];
writeFileSync(
  join(root, 'packages/shared/src/ui-source-strings.ts'),
  '/* eslint-disable */\n// Generated by scripts/sync-ui-strings.mjs from mobile/lib/core/i18n/strings_en.dart — do not edit.\n' +
    'export const UI_SOURCE_STRINGS: readonly string[] = ' +
    JSON.stringify(unique, null, 1) +
    ';\n',
);
console.log(`ui source strings: ${unique.length}`);
